#!/usr/bin/env python3
"""The gamepad drawing of the options menu: port/third_party/gamepad/controller.png (CC0) becomes
port/src/menu/menu_pad.cpp, an 8-bit mask: 255 where the picture has a dark line, 0 where it is white or a colour fill.

  python tools_pc/gen_menupad.py
"""
import os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
SRC = os.path.join(REPO, "port", "third_party", "gamepad", "controller.png")
OUT = os.path.join(REPO, "port", "src", "menu", "menu_pad.cpp")
WIDTH = 400


def main():
    im = Image.open(SRC).convert("RGBA")
    bg = Image.new("RGBA", im.size, (255, 255, 255, 255))
    bg.alpha_composite(im)
    w = WIDTH
    h = round(im.size[1] * w / im.size[0])
    rgb = bg.convert("RGB").resize((w, h), Image.LANCZOS)
    px = rgb.load()
    mask = bytearray()
    for y in range(h):
        for x in range(w):
            r, g, b = px[x, y]
            mask.append(255 - max(r, g, b))   # black lines are opaque; white and saturated fills vanish
    lines = ["// Generated by tools_pc/gen_menupad.py from port/third_party/gamepad/controller.png (CC0): do not edit.",
             '#include "menu_pad.h"', "", "const int kMenuPadW = %d;" % w, "const int kMenuPadH = %d;" % h,
             "const unsigned char kMenuPad[%d] = {" % len(mask)]
    for i in range(0, len(mask), 40):
        lines.append("  " + ",".join(str(v) for v in mask[i:i + 40]) + ",")
    lines += ["};", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", OUT, "(%dx%d)" % (w, h))


if __name__ == "__main__":
    main()
