#!/usr/bin/env python3
"""Generate port/include/bootfont.h: an 8x16 1-bit ASCII (32..126) bitmap font
for the pre-video boot screen (port/src/bootscreen.c).

Glyphs are rasterized (hinted, 1-bit) from DejaVu Sans Mono Bold, which ships
with matplotlib; DejaVu fonts are under the Bitstream Vera / DejaVu license
(free to embed, see NOTICE). Usage: gen_bootfont.py <DejaVuSansMono-Bold.ttf> <out.h>
"""
import sys
from PIL import Image, ImageDraw, ImageFont

ttf, out = sys.argv[1], sys.argv[2]
W, H = 8, 16
font = ImageFont.truetype(ttf, 13)
rows = []
for c in range(32, 127):
    im = Image.new("1", (W, H), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = "1"
    d.text((0, 0), chr(c), font=font, fill=1)
    rows.append([sum((1 << (7 - x)) for x in range(W) if im.getpixel((x, y))) for y in range(H)])
with open(out, "w", newline="\n") as f:
    f.write("/* Generated by tools_pc/gen_bootfont.py -- do not edit. 8x16, ASCII 32..126,\n"
            " * one byte per row, MSB = leftmost pixel. DejaVu Sans Mono Bold (see NOTICE). */\n"
            "#ifndef PORT_BOOTFONT_H\n#define PORT_BOOTFONT_H\n\n"
            "#define BOOTFONT_W 8\n#define BOOTFONT_H 16\n\n"
            "static const unsigned char kBootFont[95][16] = {\n")
    for c, r in zip(range(32, 127), rows):
        f.write("    {%s}, /* %s */\n" % (",".join("0x%02X" % b for b in r), "'\\'" if c == 92 else chr(c) if chr(c) != "*" and chr(c) != "/" else "star" if c == 42 else "slash"))
    f.write("};\n\n#endif\n")
# preview
for s in "GoldenEye 007 %":
    r = rows[ord(s) - 32]
    print(s); print("\n".join("".join("#" if b >> (7 - x) & 1 else "." for x in range(8)) for b in r))
