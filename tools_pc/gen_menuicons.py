#!/usr/bin/env python3
"""The face-button icons of the options menu (a PlayStation-style pad: cross, circle, square, triangle):
port/src/menu/icons/ps_*.png (plain shapes drawn for this project, white on transparent) become
port/src/menu/menu_icons.cpp, one 8-bit alpha mask per icon, in the kMenuIcon* order of menu_icons.h.

  python tools_pc/gen_menuicons.py
"""
import os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
SRC = os.path.join(REPO, "port", "src", "menu", "icons")
OUT = os.path.join(REPO, "port", "src", "menu", "menu_icons.cpp")
NAMES = ("ps_cross", "ps_circle", "ps_square", "ps_triangle")   # = kMenuIconCross .. kMenuIconTriangle
SIZE = 64


def main():
    lines = ["// Generated by tools_pc/gen_menuicons.py from port/src/menu/icons/*.png: do not edit.",
             '#include "menu_icons.h"', "", "const int kMenuIconSize = %d;" % SIZE,
             "const unsigned char kMenuIcons[%d][%d] = {" % (len(NAMES), SIZE * SIZE)]
    for n in NAMES:
        im = Image.open(os.path.join(SRC, n + ".png")).convert("RGBA")
        if im.size != (SIZE, SIZE):
            im = im.resize((SIZE, SIZE), Image.LANCZOS)
        a = im.getchannel("A").tobytes()
        lines.append("  {   // " + n)
        for i in range(0, len(a), 32):
            lines.append("    " + ",".join(str(v) for v in a[i:i + 32]) + ",")
        lines.append("  },")
    lines += ["};", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", OUT, "(%d icons, %dx%d)" % (len(NAMES), SIZE, SIZE))


if __name__ == "__main__":
    main()
