#!/usr/bin/env python3
"""Embed the menu's content: port/src/menu/menu.json becomes port/src/menu/menu_data.cpp (a byte array).

  python tools_pc/gen_menudata.py          regenerate, only if menu.json changed
  python tools_pc/gen_menudata.py --check  exit 1 if menu_data.cpp is out of date (for CI and the verify script)

The generated file carries the SHA-256 of menu.json: a run whose hash matches does nothing, so it is cheap to
call from a build, and --check needs no regeneration to answer. The JSON is also validated here (it must parse,
every control needs an id), so a typo fails the build instead of showing up as an empty menu in the game."""
import hashlib, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
SRC = os.path.join(REPO, "port", "src", "menu", "menu.json")
OUT = os.path.join(REPO, "port", "src", "menu", "menu_data.cpp")
TAG = "// menu.json sha256: "


def current_hash():
    with open(OUT, encoding="utf-8") as f:
        for line in f:
            if line.startswith(TAG):
                return line[len(TAG):].strip()
    return None


def validate(doc):
    ids = set()
    for tab in doc["tabs"]:
        for item in tab.get("items", []):
            for c in item.get("controls", []):
                cid = c.get("id")
                if not cid:
                    raise ValueError("a control has no id: " + json.dumps(c)[:80])
                if cid in ids:
                    raise ValueError("control id used twice: " + cid)
                ids.add(cid)
                if c.get("type") not in ("choice", "toggle", "slider", "action", "select", "bind", "diagram"):
                    raise ValueError(cid + ": unknown type " + str(c.get("type")))


DEF_SRC = os.path.join(REPO, "port", "src", "defaults.json")
DEF_OUT = os.path.join(REPO, "port", "src", "defaults_data.c")


def gen_defaults(check):
    """port/src/defaults.json -> port/src/defaults_data.c: two sorted tables (Switch, PC) the game and the menu share."""
    data = open(DEF_SRC, "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    have = None
    if os.path.exists(DEF_OUT):
        for line in open(DEF_OUT, encoding="utf-8"):
            if line.startswith(TAG):
                have = line[len(TAG):].strip()
    if have == digest:
        return 0
    if check:
        print("defaults_data.c is out of date: run python tools_pc/gen_menudata.py")
        return 1
    doc = json.loads(data.decode("utf-8"))["defaults"]
    tabs = {"switch": [], "pc": []}
    for key, v in doc.items():
        if isinstance(v, dict):
            per = {p: v[p] for p in ("switch", "pc") if p in v}
            if "value" in v:
                per = {"switch": v["value"], "pc": v["value"]}
        else:
            per = {"switch": v, "pc": v}
        for p, n in per.items():
            tabs[p].append((key, n))
    lines = ["// Generated by tools_pc/gen_menudata.py from defaults.json: do not edit.", TAG + digest,
             '#include "defaults.h"', ""]
    for p in ("switch", "pc"):
        lines.append("const struct DefaultEntry kDefaults%s[] = {" % p.capitalize())
        for key, n in sorted(tabs[p]):
            lines.append('  { "%s", %r },' % (key, float(n)))
        lines.append("};")
        lines.append("const int kDefaults%sCount = %d;" % (p.capitalize(), len(tabs[p])))
        lines.append("")
    full = json.loads(data.decode("utf-8"))
    version = int(full.get("version", 1))
    steps = []
    for mig in full.get("migrations", []):
        if mig["version"] > version:
            raise ValueError("migration %d is newer than the file's version %d" % (mig["version"], version))
        for st in mig["steps"]:
            if st["key"] not in doc:
                raise ValueError("migration %d: %s has no default (it can only be set or reset if defaults.json lists it)" % (mig["version"], st["key"]))
            if ("set" in st) == bool(st.get("reset")):
                raise ValueError("migration %d: %s needs exactly one of set / reset" % (mig["version"], st["key"]))
            w = st.get("when")
            steps.append((mig["version"], st["key"], 1 if st.get("reset") else 0, float(st.get("set", 0)),
                          w["key"] if w else None, float(w["eq"]) if w else 0.0))
    steps.sort(key=lambda t: t[0])
    lines.append("const int kDefaultsVersion = %d;" % version)
    lines.append("const struct DefaultMigration kDefaultMigrations[] = {")
    for v, key, reset, val, wk, we in steps:
        lines.append('  { %d, "%s", %d, %r, %s, %r },' % (v, key, reset, val, '"%s"' % wk if wk else "0", we))
    if not steps:
        lines.append("  { 0, 0, 0, 0.0, 0, 0.0 },")
    lines.append("};")
    lines.append("const int kDefaultMigrationCount = %d;" % len(steps))
    legacy = full.get("legacy", {})
    lines.append("const struct DefaultLegacy kDefaultLegacy[] = {")
    for key, n in legacy.items():
        lines.append('  { "%s", %d },' % (key, int(n)))
    if not legacy:
        lines.append("  { 0, 0 },")
    lines.append("};")
    lines.append("const int kDefaultLegacyCount = %d;" % len(legacy))
    lines.append("")
    with open(DEF_OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", DEF_OUT, "(%d switch, %d pc)" % (len(tabs["switch"]), len(tabs["pc"])))
    return 0


def main():
    r = gen_defaults("--check" in sys.argv)
    if r:
        return r
    data = open(SRC, "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    have = current_hash() if os.path.exists(OUT) else None
    if "--check" in sys.argv:
        if have != digest:
            print("menu_data.cpp is out of date: run python tools_pc/gen_menudata.py")
            return 1
        print("menu_data.cpp is up to date")
        return 0
    if have == digest:
        print("menu_data.cpp is up to date (hash " + digest[:12] + ")")
        return 0
    try:
        validate(json.loads(data.decode("utf-8")))
    except Exception as e:
        print("menu.json is invalid:", e)
        return 1
    lines = ["// Generated by tools_pc/gen_menudata.py from menu.json: do not edit.", TAG + digest,
             '#include "menu_data.h"', "", f"const char kMenuJson[{len(data) + 1}] = {{"]
    body = list(data) + [0]
    for i in range(0, len(body), 32):
        lines.append("  " + ",".join(str(b) for b in body[i:i + 32]) + ",")
    lines += ["};", f"const unsigned long kMenuJsonLen = {len(data)};", f'const char kMenuJsonSha256[] = "{digest}";', ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", OUT, f"({len(data)} bytes, hash {digest[:12]})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
