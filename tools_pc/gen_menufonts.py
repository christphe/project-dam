#!/usr/bin/env python3
"""Embed the menu's two fonts: subset the TTFs in port/third_party/fonts to the Latin glyphs the menu can show,
and write them as byte arrays to port/src/menu/menu_fonts.cpp (like gen_bootfont.py does for the boot screen).

  python tools_pc/gen_menufonts.py

Needs fontTools (pip install fonttools). Both fonts are SIL OFL 1.1 (licenses next to them); the OFL allows
subsetting and embedding provided the license text ships (NOTICE points to it)."""
import io, os, sys
from fontTools import subset
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
FONTS = os.path.join(REPO, "port", "third_party", "fonts")
OUT = os.path.join(REPO, "port", "src", "menu", "menu_fonts.cpp")

# Basic Latin, Latin-1 Supplement, Latin Extended-A, and the punctuation and symbols the menu uses.
UNICODES = list(range(0x20, 0x7F)) + list(range(0xA0, 0x180)) + [
    0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2039, 0x203A, 0x2190, 0x2191, 0x2192, 0x2193, 0x00D7, 0x00B0]

FONTS_OUT = [("kMenuBodyTtf", "FiraSans-Regular.ttf"), ("kMenuHeadTtf", "BarlowCondensed-SemiBold.ttf")]


def subset_font(path):
    opts = subset.Options()
    opts.layout_features = ["kern", "liga", "calt"]
    opts.name_IDs = [0, 1, 2, 3, 4, 6]
    opts.notdef_outline = True
    opts.hinting = False
    opts.desubroutinize = True
    font = TTFont(path)
    s = subset.Subsetter(opts)
    s.populate(unicodes=UNICODES)
    s.subset(font)
    buf = io.BytesIO()
    font.save(buf)
    return buf.getvalue()


def main():
    lines = ["// Generated by tools_pc/gen_menufonts.py: do not edit.",
             "// Latin subsets of Fira Sans Regular (Mozilla Foundation and Telefonica S.A.) and Barlow Condensed",
             "// SemiBold (The Barlow Project Authors), both SIL Open Font License 1.1: port/third_party/fonts/OFL-*.txt.",
             '#include "menu_fonts.h"', ""]
    for name, f in FONTS_OUT:
        data = subset_font(os.path.join(FONTS, f))
        lines.append(f"const unsigned char {name}[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"const unsigned long {name}Len = {len(data)};")
        lines.append("")
        print(f"{f}: {len(data)} bytes")
    with open(OUT, "w", encoding="utf-8", newline="\n") as o:
        o.write("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    sys.exit(main())
